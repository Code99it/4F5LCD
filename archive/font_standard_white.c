const int font_std_white_len = sizeof(font_std_white) / sizeof(FontChar);

// Funktion zum Suchen eines Zeichens
const FontChar* get_font_white_char(char c) {
	for (size_t i = 0; i < font_std_white_len; i++) {
	    if (font_std_white[i].character == c) {
	        return &font_std_white[i];
	    }
	}
    return NULL;
}

// Funktion zum Rendern eines Strings mit Letter-Spacing
int lcd_write_string_white(int x, int y, const char *text) {
    int cursor_x = x;
    for (const char *p = text; *p != '\0'; p++) {
        char ch = *p;

        const FontChar *found = NULL;
        for (int i = 0; i < font_std_white_len; i++) {
            if (font_std_white[i].character == ch) {
                found = &font_std_white[i];
                break;
            }
        }

        if (found) {
            lcd_draw_image(cursor_x, y, found->width, found->height, found->data);
            cursor_x += found->width + GUI_FONT_LETTER_SPACING;
        }
    }

    // Wenn am Ende kein zusätzlicher Abstand gewünscht ist, ziehe das letzte Spacing wieder ab
    if (cursor_x > x) {
        cursor_x -= GUI_FONT_LETTER_SPACING;
    }

    return cursor_x - x;
}
