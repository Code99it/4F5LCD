// Funktion zum Suchen eines Zeichens
const FontChar* get_font_gray_char(char c) {
    for (size_t i = 0; i < font_std_gray_len; i++) {
        if (font_std_gray[i].character == c) {
            return &font_std_gray[i];
        }
    }
    return NULL;
}

// Funktion zum Rendern eines Strings
int lcd_write_string_gray(int x, int y, const char *text) {
    int cursor_x = x;
    for (const char *p = text; *p != '\0'; p++) {
        char ch = *p;

        // Zeichendaten suchen
        const FontChar *found = NULL;
        for (size_t i = 0; i < font_std_gray_len; i++) {
            if (font_std_gray[i].character == ch) {
                found = &font_std_gray[i];
                break;
            }
        }

        // Wenn Zeichen gefunden, dann zeichnen und Weite + Spacing addieren
        if (found) {
            lcd_draw_image(cursor_x, y, found->width, found->height, found->data);
            cursor_x += found->width + GUI_FONT_LETTER_SPACING;
        }
    }

    // Letztes Spacing entfernen, falls mindestens ein Zeichen gezeichnet wurde
    if (cursor_x > x) {
        cursor_x -= GUI_FONT_LETTER_SPACING;
    }

    return cursor_x - x; // Gesamte Breite des Strings in Pixeln
}
